import { setSessionCookies } from '@/lib/auth/session-cookies'
import { isDefiniteRefreshFailure } from '@/lib/auth/refresh-failure'
import { COOKIE_CONSENT_COOKIE, hasOptionalCookieConsent } from '@/lib/legal/cookie-consent'
import { isAllowedApiOrigin } from '@/lib/security/origin-check'
import { getClientIpBucket } from '@/lib/security/client-ip'
import { recordSecurityEvent } from '@/lib/security/security-events'
// PROD-09: the one open-redirect guard for `next`. Its only runtime dependency is
// `node:crypto`, which the proxy's Node.js runtime provides.
import { sanitizeNextPath } from '@/lib/auth/oauth-intent'
import { adminSiteUrlFor, isAdminConsolePath } from '@/lib/admin-site'
// Phase 6: pure, dependency-light access resolver (types only — safe in the edge proxy bundle).
import { resolveLessonAccess } from '@/lib/curriculum-access'
// The proxy needs exactly one thing from the content pipeline: a slug -> lesson
// mapping, to send an authenticated learner from a public /lessons/<slug> URL to
// their interactive copy of that lesson.
//
// It used to get this via `fetchCurriculumData()` from `@/lib/lesson-loader`, which
// reads the file at runtime through `fs`. Because that path is computed at runtime,
// Next's file tracer cannot tell which files are needed and conservatively ships the
// whole compiled corpus with the proxy: 94 of the 191 traced entries were
// `content/dist` — all 90 lesson bodies plus the curriculum, glossary and id
// registry — for a branch that only runs on authenticated /lessons/... requests.
//
// Importing the curriculum index directly is the same data (it is the very file
// `fetchCurriculumData()` reads) resolved at build time instead, so the tracer ships
// one 33KB file and no `fs`/`path` dependency. Behaviour is unchanged: same lookup,
// same single redirect, same destination.
//
// `content/dist` is generated by `npm run content:build`, which the build and CI both
// run before compiling, so this resolves during the build rather than at request time.
import curriculum from '../../content/dist/curriculum.json'
import { lessonPath } from '@/lib/curriculum/lesson-url'

const AUTH_PAGE_TARGET_LEARNER = '/dashboard'
// Google sign-ups who have not yet accepted the Terms and confirmed their age land here.
const CONSENT_GATE_PAGE = '/signup/complete-consent'
const LEARNER_LOGIN_PAGE = '/login'
const ONBOARDING_PAGE = '/onboarding'

/** Signed-in app sections matched on a segment boundary (see isAppPage). */
const APP_SECTIONS = ['/badges', '/capstones', '/notifications'] as const

/**
 * The page the visitor asked for (path plus query), as a `next` value, or null when it
 * is not a safe same-origin page path (UX-07 / PROD-09).
 *
 * Built from the request URL, so it cannot point off-origin today; it still goes
 * through `sanitizeNextPath` so `/api` paths, over-long values and anything a future
 * caller passes in are dropped rather than echoed into a redirect.
 */
function returnPathOf(request: NextRequest): string | null {
  const safe = sanitizeNextPath(`${request.nextUrl.pathname}${request.nextUrl.search}`, '')
  return safe === '' ? null : safe
}

/** True for /onboarding and anything under it, ignoring the query, hash and case. */
function isOnboardingPath(value: string): boolean {
  const pathname = value.split(/[?#]/, 1)[0].toLowerCase()
  return pathname === ONBOARDING_PAGE || pathname.startsWith(`${ONBOARDING_PAGE}/`)
}

/** A redirect to `target`, carrying `next` when there is one. */
function redirectWithNext(target: string, next: string | null, request: NextRequest): NextResponse {
  const url = new URL(target, request.url)
  if (next) url.searchParams.set('next', next)
  return NextResponse.redirect(url)
}

/**
 * Attaches refreshed session cookies to a redirect/next response so a token
 * exchange performed here is not lost on the client redirect.
 *
 * B13-A: the cookie names and options moved to `lib/auth/session-cookies.ts`. This is
 * the path that keeps a session alive past the one-hour access-token lifetime now that
 * the browser no longer auto-refreshes, so it and the auth routes must agree on exactly
 * what a session cookie is — which is easier to guarantee with one definition than with
 * seven copies.
 */
function withSessionCookies(
  response: NextResponse,
  session: { access_token: string; refresh_token: string; expires_in?: number }
) {
  return setSessionCookies(response, session)
}

/**
 * Attaches the referral attribution cookie (30 days) when ?ref=CODE is detected
 * AND the visitor has consented to optional cookies.
 *
 * The consent check happens once where `refCode` is derived, so a `null` here means
 * either no code was present or consent was absent — both are "do not set".
 */
function withReferralCookie(response: NextResponse, refCode?: string | null) {
  if (!refCode) return response
  const isProd = process.env.NODE_ENV === 'production'
  response.cookies.set('prodily_referrer', refCode.trim().replace(/^@/, ''), {
    httpOnly: true,
    secure: isProd,
    sameSite: 'lax',
    path: '/',
    maxAge: 60 * 60 * 24 * 30, // 30 days
  })
  return response
}

interface ProxyUser {
  id: string
  email: string
  app_metadata: Record<string, unknown>
  user_metadata: Record<string, unknown>
  email_confirmed_at?: string
}

/**
 * Forwards the request onward with the correlation id attached (B9-B).
 *
 * `NextResponse.next({ request: { headers } })` is the supported way to hand a
 * mutated header set to the downstream handler; setting it on `request.headers`
 * directly would not survive the hop. The id is also written to the response so a
 * browser or a curl can read it back without parsing a body.
 */
function passThrough(request: NextRequest, requestId: string): NextResponse {
  const headers = new Headers(request.headers)
  headers.set(REQUEST_ID_HEADER, requestId)
  const response = NextResponse.next({ request: { headers } })
  response.headers.set(REQUEST_ID_HEADER, requestId)
  return response
}

/**
 * Entry point. Resolves the correlation id once, then runs the routing logic.
 *
 * The id is resolved here *and* independently in `withRoute`, which is deliberate
 * rather than duplicated: the proxy's matcher excludes `api/cron`, `api/health`,
 * `api/email/webhooks`, `api/email/unsubscribe`, `api/auth/callback` and `api/og`,
 * so a proxy-only implementation would leave exactly the scheduled
 * and webhook traffic untraceable. Both sides call the same resolver, so when the
 * proxy does run it stamps the header and the handler adopts that value instead of
 * minting a second one.
 */
export async function proxy(request: NextRequest) {
  const requestId = resolveRequestId(request)
  const response = await routeRequest(request, requestId)

  // Redirects and rewrites get the id on the way out too, so a redirected request
  // is still traceable from the client's side.
  if (!response.headers.has(REQUEST_ID_HEADER)) {
    response.headers.set(REQUEST_ID_HEADER, requestId)
  }
  return response
}

async function routeRequest(request: NextRequest, requestId: string): Promise<NextResponse> {
  const path = request.nextUrl.pathname
  // `prodily_referrer` is attribution, not a strictly-necessary cookie, so it is
  // only set once the visitor has accepted optional cookies. Dropping the code here
  // — rather than at each of the ~20 `withReferralCookie` call sites — keeps a
  // single gate that no future branch can forget. Attribution is not lost for a
  // consenting visitor who signs up in the same visit either way: the signup form
  // reads `?ref` from the URL directly and posts it in the request body.
  const hasCookieConsent = hasOptionalCookieConsent(request.cookies.get(COOKIE_CONSENT_COOKIE)?.value)
  const refParam = hasCookieConsent ? request.nextUrl.searchParams.get('ref') : null
  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://mock.supabase.co'
  const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || 'mock-anon-key'

  // ── Admin console: moved to its own host ────────────────────────────────
  // A stale /admin bookmark is sent to the same path on ADMIN_SITE_URL with a 308. With
  // no admin host configured it passes through, and since this app has no /admin route
  // Next answers with the not-found page and a 404. No session work happens either way.
  if (isAdminConsolePath(path)) {
    const target = adminSiteUrlFor(`${path}${request.nextUrl.search}`)
    if (target) return NextResponse.redirect(target, 308)
    return passThrough(request, requestId)
  }

  // Route classification ----------------------------------------------------
  // The consent gate sits under /signup but is only for signed-in users, so it is
  // handled before the general auth-page bounce below.
  const isConsentGatePage = path === CONSENT_GATE_PAGE

  // Auth pages are public and route authenticated users away.
  const isGeneralAuthPage =
    path.startsWith('/login') || path.startsWith('/signup') || path.startsWith('/reset-password')

  // L1: badges, capstones and notifications (all under app/(app)) were missing, so
  // maintenance mode, onboarding and the Google consent gate skipped them.
  // lib/__tests__/proxy-app-pages.test.ts fails when a new (app) segment is not covered.
  const isAppPage =
    APP_SECTIONS.some((section) => path === section || path.startsWith(`${section}/`)) ||
    path.startsWith('/dashboard') ||
    (path === '/review' || path.startsWith('/review/')) ||
    path.startsWith('/progress') ||
    path.startsWith('/leaderboard') ||
    path.startsWith('/settings') ||
    path.startsWith('/onboarding') ||
    path.startsWith('/academy') ||
    (path.startsWith('/curriculum/') && path !== '/curriculum')

  const isPublicPage = isGeneralAuthPage

  // Learner APIs that must be protected against maintenance mode & unverified bypass
  const isApiRoute = path.startsWith('/api/')
  const isExemptApi =
    path.startsWith('/api/auth/') ||
    path.startsWith('/api/cron/') ||
    // Server-to-server calls from the admin console, authenticated by a shared secret.
    path.startsWith('/api/internal/') ||
    path.startsWith('/api/email/') ||
    path === '/api/contact' ||
    // ENG-11: the error-boundary beacon. It reads no session, so verifying one here
    // would cost an auth call per crash report, and the maintenance and consent gates
    // would drop the very reports that explain an outage.
    path === '/api/client-errors'
  const isProtectedLearnerApi = isApiRoute && !isExemptApi

  // SEC-12: Enforce same-origin writes for cookie-authenticated API requests
  if (isApiRoute && !isAllowedApiOrigin(request, path)) {
    recordSecurityEvent('origin_rejected', { ipBucket: getClientIpBucket(request), path })
    return NextResponse.json(
      {
        success: false,
        error: 'Cross-origin request forbidden.',
        code: 'FORBIDDEN',
        requestId,
      },
      { status: 403, headers: { [REQUEST_ID_HEADER]: requestId } }
    )
  }

  // Maintenance page must always be reachable so learners see the correct message
  if (path === '/maintenance') {
    return withReferralCookie(passThrough(request, requestId), refParam)
  }

  // Authenticated learners navigating to public /curriculum are routed to their interactive academy
  if (path === '/curriculum') {
    const hasAuthToken = Boolean(
      request.cookies.get('sb-access-token')?.value || request.cookies.get('sb-refresh-token')?.value
    )
    if (hasAuthToken) {
      return withReferralCookie(NextResponse.redirect(new URL('/academy', request.url)), refParam)
    }
  }

  // Authenticated learners navigating to public /lessons/[slug].
  //
  // Phase 6 (public-lesson access paradox): the public /lessons/<slug> page is a read-only,
  // statically-cached PREVIEW. Previously every authenticated visitor was redirected to the
  // interactive /academy lesson, where the curriculum gate could then drop them onto a lock
  // wall — content they could already read publicly. We now upgrade them to the interactive
  // lesson ONLY when it is actually accessible, computed with the CONTROL (global-sequential)
  // model plus grandfathering/override. Control access is a strict subset of the module-entry
  // treatment access, so a redirect can never land the learner on a lock wall under either arm.
  // When the interactive lesson is not yet accessible, the learner simply keeps reading the
  // public preview (no lock wall, and the preview exposes no progress/quiz/XP mutation).
  if (path.startsWith('/lessons/')) {
    const accessToken = request.cookies.get('sb-access-token')?.value
    const refreshToken = request.cookies.get('sb-refresh-token')?.value
    if (accessToken || refreshToken) {
      const slug = path.replace(/^\/lessons\//, '').split('/')[0]
      const match = slug ? curriculum.lessons.find((l) => l.slug === slug) : null
      const academyUrl = match
        ? new URL(lessonPath(match.module, match.id), request.url)
        : new URL('/academy', request.url)

      if (match) {
        const supabase = createClient(supabaseUrl, supabaseAnonKey, {
          auth: { persistSession: false },
        })

        // Verify the learner from the access token only, so the access check reflects their
        // real completion state rather than mere cookie presence. We deliberately do NOT call
        // refreshSession here: GoTrue rotates (revokes) the refresh token on use, and this
        // branch does not write cookies back, so refreshing would leave the browser holding a
        // revoked token and log the learner out. When the access token is missing/expired,
        // verifiedUserId stays null and we fall through to the redirect-to-academy path below,
        // where the main proxy flow refreshes AND persists the session correctly.
        const bearer: string | undefined = accessToken
        let verifiedUserId: string | null = null
        try {
          if (accessToken) {
            const { data, error } = await supabase.auth.getClaims(accessToken)
            if (!error && data?.claims?.sub) verifiedUserId = data.claims.sub
          }
        } catch (err) {
          console.error('[proxy] /lessons access-check auth error:', err)
        }

        if (verifiedUserId) {
          let accessible = false
          try {
            const authed = createClient(supabaseUrl, supabaseAnonKey, {
              global: { headers: bearer ? { Authorization: `Bearer ${bearer}` } : {} },
              auth: { persistSession: false },
            })
            const [{ data: rows }, { data: urow }] = await Promise.all([
              authed.from('user_lesson_progress').select('lesson_id, status').eq('user_id', verifiedUserId),
              authed.from('users').select('curriculum_access_override').eq('id', verifiedUserId).maybeSingle(),
            ])
            const completedIds = new Set<string>()
            const openedIds = new Set<string>()
            for (const r of (rows ?? []) as { lesson_id: string; status: string }[]) {
              openedIds.add(r.lesson_id)
              if (r.status === 'completed') completedIds.add(r.lesson_id)
            }
            const info = resolveLessonAccess(match.id, {
              curriculum: curriculum.lessons,
              completedIds,
              openedIds,
              treatment: false, // control model = strict subset of treatment access
              override: Boolean((urow as { curriculum_access_override?: boolean } | null)?.curriculum_access_override),
            })
            accessible = info.isAccessible
          } catch (err) {
            console.error('[proxy] /lessons access-check query error:', err)
          }

          // Accessible → upgrade to the interactive lesson; otherwise keep the public preview.
          return accessible
            ? withReferralCookie(NextResponse.redirect(academyUrl), refParam)
            : withReferralCookie(passThrough(request, requestId), refParam)
        }
        // Verification failed (transient) — preserve the prior convenience: route to academy,
        // where the lesson page's own gate/lock screen handles access safely.
        return withReferralCookie(NextResponse.redirect(academyUrl), refParam)
      }

      // Unknown slug with a session — preserve prior behaviour (send to the curriculum).
      return withReferralCookie(NextResponse.redirect(academyUrl), refParam)
    }
  }

  // Fast path for non-guarded public routes
  if (!isPublicPage && !isAppPage && !isProtectedLearnerApi) {
    return withReferralCookie(passThrough(request, requestId), refParam)
  }

  const accessToken = request.cookies.get('sb-access-token')?.value
  const refreshToken = request.cookies.get('sb-refresh-token')?.value

  let user: ProxyUser | null = null
  let newSession: { access_token: string; refresh_token: string; expires_in?: number } | null = null
  // True when the refresh could not be decided (network error, auth server 5xx). The
  // refresh cookie may still be valid, so it must not be deleted.
  let refreshUnavailable = false

  // 1. Verify access token with Supabase GoTrue
  if (accessToken || refreshToken) {
    const supabase = createClient(supabaseUrl, supabaseAnonKey, {
      auth: { persistSession: false },
    })

    if (accessToken) {
      try {
        type AuthWithGetClaims = {
          getClaims?: (token: string) => Promise<{
            data: { claims?: Record<string, unknown> } | null
            error: unknown
          }>
        }
        const authWithClaims = supabase.auth as unknown as AuthWithGetClaims
        if (typeof authWithClaims.getClaims === 'function') {
          const { data, error } = await authWithClaims.getClaims(accessToken)
          const claims = data?.claims
          if (!error && claims?.sub && typeof claims.sub === 'string') {
            user = {
              id: claims.sub,
              email: typeof claims.email === 'string' ? claims.email : '',
              app_metadata: (claims.app_metadata as Record<string, unknown>) || {},
              user_metadata: (claims.user_metadata as Record<string, unknown>) || {},
              email_confirmed_at:
                typeof claims.email_confirmed_at === 'string'
                  ? claims.email_confirmed_at
                  : claims.email
                    ? 'confirmed'
                    : undefined,
            }
          }
        } else {
          const { data, error } = await supabase.auth.getUser(accessToken)
          if (!error && data?.user) {
            user = {
              id: data.user.id,
              email: data.user.email || '',
              app_metadata: data.user.app_metadata || {},
              user_metadata: data.user.user_metadata || {},
              email_confirmed_at: data.user.email_confirmed_at,
            }
          }
        }
      } catch (err) {
        console.error('[proxy] auth verification error:', err)
      }
    }

    // 2. Fallback: If access token was missing, expired, or invalid, attempt refresh token
    if (!user && refreshToken) {
      try {
        const { data, error } = await supabase.auth.refreshSession({ refresh_token: refreshToken })
        if (error && !isDefiniteRefreshFailure(error)) refreshUnavailable = true
        if (!error && data?.session && data?.user) {
          user = {
            id: data.user.id,
            email: data.user.email || '',
            app_metadata: (data.user.app_metadata as Record<string, unknown>) || {},
            user_metadata: (data.user.user_metadata as Record<string, unknown>) || {},
            email_confirmed_at: data.user.email_confirmed_at,
          }
          newSession = data.session
        }
      } catch (err) {
        refreshUnavailable = true
        console.error('[proxy] Refresh session error:', err)
      }
    }
  }

  type ProfileData = {
    curriculum_access_override?: boolean
    auth_provider?: string
    terms_accepted_at?: string | null
    onboarding_completed?: boolean
    goal?: string | null
  }
  let cachedUserData: ProfileData | null = null
  let profileLookupFailed = false
  async function loadUserProfileData() {
    if (!user) return null
    if (cachedUserData !== null) return cachedUserData
    try {
      const activeAccessToken = newSession?.access_token ?? accessToken
      const authorizedClient = createClient(supabaseUrl, supabaseAnonKey, {
        global: {
          headers: activeAccessToken ? { Authorization: `Bearer ${activeAccessToken}` } : {},
        },
        auth: { persistSession: false },
      })

      const { data, error } = await authorizedClient
        .from('users')
        .select('curriculum_access_override, auth_provider, terms_accepted_at, onboarding_completed, goal')
        .eq('id', user.id)
        .maybeSingle()
      if (error) {
        profileLookupFailed = true
        console.error('[proxy] User profile database check error:', { userId: user.id, code: error.code, message: error.message })
      }
      cachedUserData = (data || {}) as ProfileData
      return cachedUserData
    } catch (err) {
      console.error('[proxy] User profile database check error:', err)
      profileLookupFailed = true
      cachedUserData = {}
      return cachedUserData
    }
  }

  /**
   * True when the signed `app_metadata.is_admin` JWT claim is set. Email addresses never
   * grant admin, and there is no database fallback: the console lives on its own host,
   * and on this host the flag only lets an admin who uses the learner app past
   * maintenance mode, the email-verification gate and the consent gate (0 DB calls).
   */
  function isAdmin(): boolean {
    return user?.app_metadata?.is_admin === true
  }

  async function hasCurriculumAccessOverride(): Promise<boolean> {
    if (!user) return false
    // SEC-21: Trusted claim in app_metadata only (user_metadata is client-writable)
    if (user.app_metadata?.curriculum_access_override === true) return true

    const profileData = await loadUserProfileData()
    return Boolean(profileData?.curriculum_access_override)
  }

  /**
   * True only for a Google sign-up whose profile has no recorded Terms/age consent.
   *
   * The verified user's provider list is checked first, so password users never pay for
   * a profile query here. A merged password account keeps auth_provider 'email' and is
   * never gated, nor is a legacy password user with null consent. A failed or missing
   * profile read answers false: the gate fails open rather than locking learners out.
   *
   * Perf plan item 16: /api/auth/complete-consent writes `app_metadata.terms_accepted`
   * once consent is recorded, so a token carrying that signed claim skips the profile
   * read. app_metadata is only writable with the service role, so the claim is trusted
   * like `is_admin`. Tokens minted before the claim existed fall back to the read.
   */
  let consentFailOpenLogged = false
  async function needsConsent(): Promise<boolean> {
    if (!user) return false
    const providers = user.app_metadata?.providers
    const signedInWithGoogle =
      user.app_metadata?.provider === 'google' || (Array.isArray(providers) && providers.includes('google'))
    if (!signedInWithGoogle) return false
    if (user.app_metadata?.terms_accepted === true) return false

    const profileData = await loadUserProfileData()
    // auth_provider is NOT NULL, so its absence means the read failed or the row is missing.
    if (profileData?.auth_provider === undefined) {
      if (!consentFailOpenLogged) {
        consentFailOpenLogged = true
        console.warn('[proxy] consent gate failed open: profile unavailable', { userId: user.id })
      }
      return false
    }
    return profileData.auth_provider === 'google' && profileData.terms_accepted_at == null
  }

  // ── Consent gate page: signed-in Google users without consent only ───────
  if (isConsentGatePage) {
    if (!user) {
      return withReferralCookie(redirectWithNext(LEARNER_LOGIN_PAGE, returnPathOf(request), request), refParam)
    }

    const response = (await needsConsent())
      ? passThrough(request, requestId)
      : NextResponse.redirect(new URL(AUTH_PAGE_TARGET_LEARNER, request.url))
    const sessionRes = newSession ? withSessionCookies(response, newSession) : response
    return withReferralCookie(sessionRes, refParam)
  }

  // ── Password Reset Update Mode (Recovery session in progress) ────────────
  // When a user verifies their reset link, they arrive at /reset-password?mode=update
  // with an active recovery session. They MUST be allowed to remain on this page
  // to choose their new password.
  if (path === '/reset-password' && request.nextUrl.searchParams.get('mode') === 'update') {
    if (!user) {
      // If recovery session is missing or expired, redirect to request form
      return withReferralCookie(NextResponse.redirect(new URL('/reset-password?error=expired', request.url)), refParam)
    }
    const response = newSession ? withSessionCookies(passThrough(request, requestId), newSession) : passThrough(request, requestId)
    return withReferralCookie(response, refParam)
  }

  // ── Public auth pages (/login, /signup, /reset-password) ─────────────────
  if (isGeneralAuthPage) {
    if (!user) return withReferralCookie(passThrough(request, requestId), refParam)

    // Authenticated users are routed away to the learner dashboard, admins included:
    // the admin console is on its own host (ADMIN_SITE_URL) with its own login.
    const response = NextResponse.redirect(new URL(AUTH_PAGE_TARGET_LEARNER, request.url))
    const sessionRes = newSession ? withSessionCookies(response, newSession) : response
    return withReferralCookie(sessionRes, refParam)
  }

  // ── Protected learner API routes (maintenance & email verification) ─────
  if (isProtectedLearnerApi) {
    const { SettingsService } = await import('@/lib/settings/system-settings-service')
    const productSettings = await SettingsService.getProductSettings()

    // 1. Maintenance mode enforcement on APIs: 503 Service Unavailable for non-admins
    if (productSettings.maintenanceMode && !isAdmin()) {
      return NextResponse.json(
        {
          error: 'The platform is currently undergoing scheduled maintenance. Please check back shortly.',
          code: 'MAINTENANCE_MODE',
        },
        { status: 503 }
      )
    }

    // 2. Email verification enforcement on APIs: 403 Forbidden for unverified learners
    if (productSettings.requireEmailVerification && user && !user.email_confirmed_at && !isAdmin()) {
      return NextResponse.json(
        {
          error: 'Please verify your email address before accessing platform features.',
          code: 'AUTH_EMAIL_NOT_CONFIRMED',
        },
        { status: 403 }
      )
    }

    // 3. Google sign-ups must accept the Terms before using learner APIs.
    if (!isAdmin() && (await needsConsent())) {
      const response = NextResponse.json(
        {
          error: 'Please accept the Terms and confirm your age before continuing.',
          code: 'CONSENT_REQUIRED',
        },
        { status: 403 }
      )
      return newSession ? withSessionCookies(response, newSession) : response
    }

    if (newSession) {
      return withReferralCookie(withSessionCookies(passThrough(request, requestId), newSession), refParam)
    }
    return withReferralCookie(passThrough(request, requestId), refParam)
  }

  // ── Protected application routes ─────────────────────────────────────────
  if (isAppPage) {
    if (!user) {
      if (refreshUnavailable) {
        // The auth server could not be reached. Keep the cookies and ask the browser to
        // retry, instead of signing the learner out over a temporary outage.
        return new NextResponse(
          '<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="5"><title>Reconnecting</title><p style="font-family:system-ui,sans-serif;padding:2rem">We could not reach the sign-in service. Retrying in a few seconds...</p>',
          {
            status: 503,
            headers: { 'content-type': 'text/html; charset=utf-8', 'retry-after': '5', 'cache-control': 'no-store' },
          }
        )
      }
      // Learners come back to the page they asked for after signing in.
      const response = redirectWithNext(LEARNER_LOGIN_PAGE, returnPathOf(request), request)
      response.cookies.delete('sb-access-token')
      response.cookies.delete('sb-refresh-token')
      return withReferralCookie(response, refParam)
    }

    // ── Email verification check for learner protected routes ────────────────
    if (!isAdmin()) {
      const { SettingsService } = await import('@/lib/settings/system-settings-service')
      const productSettings = await SettingsService.getProductSettings()

      // Maintenance mode — block all non-admin learners from the app
      if (productSettings.maintenanceMode) {
        const response = NextResponse.redirect(new URL('/maintenance', request.url))
        const sessionRes = newSession ? withSessionCookies(response, newSession) : response
        return withReferralCookie(sessionRes, refParam)
      }

      // Email verification enforcement
      if (productSettings.requireEmailVerification && !user.email_confirmed_at) {
        const response = NextResponse.redirect(new URL('/login?error=email_not_confirmed', request.url))
        const sessionRes = newSession ? withSessionCookies(response, newSession) : response
        return withReferralCookie(sessionRes, refParam)
      }

      // Google sign-ups must accept the Terms before anything else, onboarding included.
      if (await needsConsent()) {
        const gateUrl = new URL(CONSENT_GATE_PAGE, request.url)
        gateUrl.searchParams.set('next', path)
        const response = NextResponse.redirect(gateUrl)
        const sessionRes = newSession ? withSessionCookies(response, newSession) : response
        return withReferralCookie(sessionRes, refParam)
      }
    }

    // SEC-21: Trusted claim in app_metadata OR database public.users columns.
    // Stop reading user_metadata for access decisions.
    let isOnboardingComplete = Boolean(
      user.app_metadata?.onboarding_complete === true ||
      user.app_metadata?.onboarding_completed === true
    )
    let onboardingStateUnknown = false
    if (!isOnboardingComplete) {
      const profileData = await loadUserProfileData()
      isOnboardingComplete = Boolean(
        profileData?.onboarding_completed ||
        profileData?.goal != null ||
        profileData?.curriculum_access_override
      )
      // A failed profile read must not send an onboarded learner back to onboarding: fail open,
      // like the consent gate. A missing row (no error) still goes to onboarding.
      onboardingStateUnknown = !isOnboardingComplete && profileLookupFailed
      if (onboardingStateUnknown) {
        console.warn('[proxy] onboarding gate failed open: profile unavailable', { userId: user.id })
      }
    }
    const isOnboardingPage = path === ONBOARDING_PAGE

    if (!isOnboardingComplete && !onboardingStateUnknown && !isOnboardingPage && !(await hasCurriculumAccessOverride())) {
      // Force onboarding goal selection for learners (override users are unaffected).
      // The page they asked for rides along as `next` so onboarding can finish there. The
      // dashboard is onboarding's default anyway, and an /onboarding path as `next` would
      // only send the learner back to onboarding, so neither is carried.
      const next = path === AUTH_PAGE_TARGET_LEARNER || isOnboardingPath(path) ? null : returnPathOf(request)
      const response = redirectWithNext(ONBOARDING_PAGE, next, request)
      const sessionRes = newSession ? withSessionCookies(response, newSession) : response
      return withReferralCookie(sessionRes, refParam)
    }

    if (isOnboardingComplete && isOnboardingPage) {
      // Skip onboarding since it is already complete, honouring a safe `next`. A `next`
      // back into onboarding falls to the dashboard so this can never redirect to itself.
      const requested = sanitizeNextPath(request.nextUrl.searchParams.get('next'), AUTH_PAGE_TARGET_LEARNER)
      const target = isOnboardingPath(requested) ? AUTH_PAGE_TARGET_LEARNER : requested
      const response = NextResponse.redirect(new URL(target, request.url))
      const sessionRes = newSession ? withSessionCookies(response, newSession) : response
      return withReferralCookie(sessionRes, refParam)
    }

    if (newSession) {
      return withReferralCookie(withSessionCookies(passThrough(request, requestId), newSession), refParam)
    }

    return withReferralCookie(passThrough(request, requestId), refParam)
  }

  return withReferralCookie(passThrough(request, requestId), refParam)
}

/**
 * Which requests enter the session proxy at all.
 *
 * Entering this proxy is not free: Vercel bills it as its own function invocation, so
 * a request that reaches a page costs two. Every path listed below authenticates
 * itself independently and reads nothing from the session, so running session
 * verification for it bought nothing.
 *
 * This narrows only which paths enter: it does not change what the proxy does for
 * anything that still enters. Verified getClaims(), refresh-session handling, cookie
 * clearing and protected-page redirects are all untouched (B3).
 *
 * Excluded paths, each verified route-by-route rather than by pathname assumption:
 *
 *   api/cron/*              CRON_SECRET bearer only (the scheduler, or the admin
 *                           console calling from its server).
 *   api/internal/*          Shared-secret bearer (INTERNAL_REVALIDATE_SECRET) from the
 *                           admin console's server. No session, no cookies.
 *   api/health              No auth of any kind; returns a liveness probe. A health
 *                           check should also answer during maintenance mode.
 *   api/og/*                Deliberately public: social crawlers must fetch it
 *                           unauthenticated. Portfolio privacy is enforced inside the
 *                           handler, not here.
 *   api/email/webhooks      Svix (Resend) / shared-secret (Brevo) signature auth.
 *   api/email/unsubscribe   One-time `unsubscribe_token` from the email itself.
 *   public marketing pages  about, contact, faq, frameworks, glossary, privacy,
 *                           reviews, terms, waitlist: static marketing content
 *                           with no session dependency.
 *
 * `api/email/*` is listed as its two concrete routes rather than as a namespace on
 * purpose: they authenticate by two different mechanisms, and a future
 * session-backed route added under that prefix must NOT inherit an exclusion by
 * accident.
 *
 * Conditional public pages (perf plan item 15). For an anonymous visitor without `?ref`
 * the proxy did nothing on these but stamp the request id and pass through, so they no
 * longer enter it unconditionally. They enter only when the proxy has work to do:
 *
 *   /, /curriculum, /lessons/*   with an `sb-access-token` or `sb-refresh-token` cookie.
 *                                /curriculum and /lessons/* redirect signed-in learners to
 *                                /academy. `/` has no session branch today; it stays
 *                                matched for signed-in visitors so a future one is not
 *                                silently skipped.
 *   all of the above, plus       with a `?ref` query AND a cookie-consent cookie: the
 *   /maintenance, /verify/*,     referral cookie. The proxy still checks the consent value
 *   /p/*                         itself; the matcher only requires the cookie to exist.
 *
 * `has` entries are ANDed within one matcher object and the matcher objects are ORed,
 * which is why each cookie gets its own entry. Maintenance mode is unaffected: the proxy
 * enforces it only on app pages and learner APIs, never on these public pages. Static
 * security headers (CSP and friends) come from next.config.ts, not from here.
 *
 * Everything else still matches unconditionally: app pages, /admin (redirected or 404),
 * /curriculum/<module>,
 * auth pages, and every API route outside the exclusions above (SEC-12 origin check).
 */
export const config = {
  matcher: [
    /*
     * Match all paths except:
     * - API routes that carry their own independent authentication (see above)
     * - Public marketing pages (about, contact, faq, frameworks, glossary, privacy, reviews, terms, waitlist)
     * - The conditional public pages (root, curriculum, lessons, maintenance, verify, p),
     *   which the entries below match only when the proxy has work to do
     * - static files (css, js, images, robots, sitemap)
     * - favicon.ico
     */
    '/((?!(?:_next/static|_next/image|content|brand|api/auth/callback|api/cron|api/internal|api/health|api/og|api/email/webhooks|api/email/unsubscribe|about|contact|faq|frameworks|glossary|privacy|reviews|terms|waitlist)(?:/|$)|(?:favicon\\.ico|robots\\.txt|sitemap\\.xml|maintenance|curriculum)$|verify/|p/|lessons/|$|[^/]*\\.[^/]*$).*)',
    { source: '/', has: [{ type: 'cookie', key: 'sb-access-token' }] },
    { source: '/', has: [{ type: 'cookie', key: 'sb-refresh-token' }] },
    {
      source: '/',
      has: [
        { type: 'query', key: 'ref' },
        { type: 'cookie', key: 'prodily_cookie_consent' },
      ],
    },
    { source: '/:sessionPath(curriculum|lessons/.+)', has: [{ type: 'cookie', key: 'sb-access-token' }] },
    { source: '/:sessionPath(curriculum|lessons/.+)', has: [{ type: 'cookie', key: 'sb-refresh-token' }] },
    {
      source: '/:refPath(curriculum|maintenance|lessons/.+|verify/.+|p/.+)',
      has: [
        { type: 'query', key: 'ref' },
        { type: 'cookie', key: 'prodily_cookie_consent' },
      ],
    },
  ],
}
