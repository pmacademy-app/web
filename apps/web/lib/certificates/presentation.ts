/**
 * How a certificate is worded on screen (pure, client-safe).
 *
 * Admin dev TEST- certificates live in the same `certificates` table and resolve on the
 * same /verify route as real credentials. Every surface that lists or verifies a
 * certificate asks here what to call it, so a TEST row is never worded as a verified
 * credential.
 */
import { BRAND } from '@/lib/brand'
import { isTestCertificateCode } from '@/lib/certificates'
import { CURRICULUM_MODULE_META } from '@/lib/admin/curriculum-meta'

export const VERIFIED_CREDENTIAL_LABEL = 'Verified Credential'
export const TEST_CERTIFICATE_LABEL = 'Test certificate (not a valid credential)'
export const TEST_CERTIFICATE_EXPLANATION =
  'Generated by an administrator to test certificate delivery. It does not certify any completed lessons.'

/**
 * What a real certificate states about its recipient. A certificate is earned by completing
 * all 90 lessons; capstones are not required and nothing is assessed as "mastery", so the
 * card claims completion only.
 */
export const CERTIFICATE_RECIPIENT_LEAD_IN = 'This credential is awarded to'
export const CERTIFICATE_COMPLETION_STATEMENT =
  'for completing all 90 lessons across 9 modules of the curriculum.'

/** The exact requirement, stated on /verify so a reader knows what the certificate measures. */
export const CERTIFICATE_REQUIREMENT_STATEMENT = 'Awarded for completing all 90 lessons.'
export const MODULE_CERTIFICATE_REQUIREMENT_STATEMENT = 'Awarded for completing every lesson in one module.'

export interface CertificatePresentation {
  isTest: boolean
  /** Status shown beside the certificate code. */
  statusLabel: string
  /** False for a TEST row: no LinkedIn or share prompts, no credential JSON-LD. */
  isShareableCredential: boolean
}

export function getCertificatePresentation(certificateCode: string): CertificatePresentation {
  const isTest = isTestCertificateCode(certificateCode)
  return {
    isTest,
    statusLabel: isTest ? TEST_CERTIFICATE_LABEL : VERIFIED_CREDENTIAL_LABEL,
    isShareableCredential: !isTest,
  }
}

export interface VerifyPageCopyInput {
  certificateCode: string
  learnerName: string
  careerTitle: string
  lessonsCompleted: number
}

export interface VerifyPageCopy extends CertificatePresentation {
  metaTitle: string
  metaDescription: string
  /** Search engines may index the page. Never for a TEST row. */
  indexable: boolean
  /** First line of the page footer. */
  footerLine: string
}

/** Metadata and footer wording for /verify/[certificateId]. */
export function getVerifyPageCopy({
  certificateCode,
  learnerName,
  careerTitle,
  lessonsCompleted,
}: VerifyPageCopyInput): VerifyPageCopy {
  const presentation = getCertificatePresentation(certificateCode)

  if (presentation.isTest) {
    return {
      ...presentation,
      metaTitle: TEST_CERTIFICATE_LABEL,
      metaDescription: `${TEST_CERTIFICATE_LABEL}. ${TEST_CERTIFICATE_EXPLANATION} Certificate ID: ${certificateCode}.`,
      indexable: false,
      footerLine: `${TEST_CERTIFICATE_LABEL}. Generated for internal testing.`,
    }
  }

  return {
    ...presentation,
    metaTitle: `Verified Certificate: ${learnerName} | ${careerTitle}`,
    metaDescription: `Official ${BRAND.fullName} Certificate of Completion for ${learnerName} (${careerTitle}, ${lessonsCompleted} lessons completed). Certificate ID: ${certificateCode}.`,
    indexable: true,
    footerLine: `Official Verified Credential. ${BRAND.certificateIssuerLine}.`,
  }
}

export interface CertificateRowCopyInput {
  type: string
  module_slug: string | null
  lessons_completed: number
  level: number
  career_title: string
  issued_at: string
}

/**
 * Title and detail line for a real certificate in a list. A module certificate is titled by its
 * module; only the full-curriculum certificate is called a curriculum completion certificate.
 */
export function getCertificateRowCopy(cert: CertificateRowCopyInput): { title: string; detail: string } {
  const issued = new Date(cert.issued_at).toLocaleDateString()
  if (cert.type !== 'full_curriculum') {
    const moduleName = cert.module_slug ? CURRICULUM_MODULE_META[cert.module_slug]?.name : undefined
    return moduleName
      ? {
          title: `${moduleName} Module Certificate`,
          detail: `Issued on ${issued} for completing every lesson in ${moduleName}.`,
        }
      : { title: 'Module Certificate', detail: `Issued on ${issued} for completing every lesson in a module.` }
  }
  return {
    title: `${BRAND.fullName} Full Curriculum Completion Certificate`,
    detail: `Issued on ${issued} for completing all ${cert.lessons_completed} lessons and reaching Level ${cert.level} (${cert.career_title}).`,
  }
}
